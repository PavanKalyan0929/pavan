/**
 * Generates clearly-labelled DEMO placeholder entries across all 26 Andhra Pradesh districts
 * alongside verified institutions so the combined directory scales past 420 records without
 * ever fabricating real institution codes or affiliations.
 */
export function buildDemoColleges(totalPlaceholders = 400): CollegeRecord[] {
  const colleges: CollegeRecord[] = [...VERIFIED_AP_COLLEGES];
  for (let i = 0; i < totalPlaceholders; i++) {
    const num = i + 1;
    const codeNumber = String(num).padStart(3, '0');
    const district = AP_DISTRICTS[i % AP_DISTRICTS.length];
    const template = INSTITUTE_TEMPLATES[i % INSTITUTE_TEMPLATES.length];
    const management = MANAGEMENT_TYPES[i % MANAGEMENT_TYPES.length];
    const locality = TOWN_LOCALITIES[(i * 3) % TOWN_LOCALITIES.length];
    const clusterIndex = Math.floor(i / AP_DISTRICTS.length) + 1;
    const shortDistrict = district.replace('Dr. B.R. Ambedkar ', '').replace('Sri Potti Sriramulu ', '');

    colleges.push({
      id: `demo-ap-${codeNumber}`,
      code: `AP-DEMO-${codeNumber}`,
      name: `[DEMO] ${shortDistrict} ${template.suffix} (${clusterIndex})`,
      location: shortDistrict,
      district,
      address: `Demo Campus Plot ${10 + (i % 89)}, ${locality}, ${district} District, Andhra Pradesh (Sample Entry)`,
      website: '',
      contactEmail: 'Pending institutional verification',
      contactPhone: 'Pending institutional verification',
      management,
      category: template.category,
      affiliatedUniversity: template.university,
      accreditation: template.accreditation,
      verificationStatus: 'DEMO',
      isDemo: true,
      coursesCount: template.courses.length,
      courses: template.courses,
      departments: template.departments,
      sourceUrl: '',
      lastVerifiedDate: '',
      integrationStatus: 'Requires Integration',
      integrationAdapter: 'None',
      adminEmails: [],
    });
  }
  return colleges;
}

