export interface CollegeMediaSummary {
  collegeId: string;
  logo: CollegeMediaRecord | null;
  primaryCampusPhoto: CollegeMediaRecord | null;
  studentActivityPhotos: CollegeMediaRecord[];
  approvedPhotos: CollegeMediaRecord[];
  totalApprovedCount: number;
}

/**
 * Merges seeded verified public photographs with live State-Admin-approved Firestore records,
 * strictly keyed by each record's exact collegeId so one institution never inherits another's photo.
 */
export function buildCollegeMediaSummaryMap(
  liveApprovedMedia: CollegeMediaRecord[] = []
): Record<string, CollegeMediaSummary> {
  const combinedById = new Map<string, CollegeMediaRecord>();
  for (const item of VERIFIED_SEEDED_MEDIA) {
    if (item.approvalStatus === 'Approved') {
      combinedById.set(item.id, item);
    }
  }
  for (const item of liveApprovedMedia) {
    if (item && item.id && item.collegeId && item.approvalStatus === 'Approved') {
      combinedById.set(item.id, item);
    }
  }

  const byCollege: Record<string, CollegeMediaRecord[]> = {};
  for (const item of combinedById.values()) {
    if (!byCollege[item.collegeId]) {
      byCollege[item.collegeId] = [];
    }
    byCollege[item.collegeId].push(item);
  }

  const summaryMap: Record<string, CollegeMediaSummary> = {};
  for (const [collegeId, items] of Object.entries(byCollege)) {
    const logo = items.find((m) => m.mediaCategory === 'Official Logo') || null;
    const primaryCampusPhoto =
      items.find((m) => m.mediaCategory === 'Main Campus & Entrance') ||
      items.find((m) => m.mediaCategory === 'Academic Building') ||
      items.find((m) => m.mediaCategory !== 'Official Logo') ||
      null;
    const studentActivityPhotos = items.filter((m) =>
      STUDENT_INTERACTION_CATEGORIES.has(m.mediaCategory)
    );

    summaryMap[collegeId] = {
      collegeId,
      logo,
      primaryCampusPhoto,
      studentActivityPhotos,
      approvedPhotos: items,
      totalApprovedCount: items.length,
    };
  }

  return summaryMap;
}
